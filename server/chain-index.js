import {readFile,mkdir} from 'node:fs/promises';
import {dirname} from 'node:path';
import {createChainApp} from './chain-app.js';
import {networkFor} from '../shared/networks.js';
const chainId=Number(process.env.CHAIN_ID||31337),network=networkFor(chainId);
const filename=process.env.CHAIN_DATABASE_PATH||`server/data/${chainId===31337?'chain':'sepolia'}.sqlite`;
const manifest=process.env.CHAIN_MANIFEST_PATH||`blockchain/deployments/${chainId===31337?'localhost':'sepolia'}.json`;
const rpcUrl=process.env.CHAIN_RPC_URL||network.rpcUrl;
const port=Number(process.env.CHAIN_API_PORT||(chainId===31337?3002:3003));
const origin=process.env.APP_ORIGIN||`http://127.0.0.1:${chainId===31337?5174:5175}`;
await mkdir(dirname(filename),{recursive:true});
const app=createChainApp({filename,origin,rpcUrl,chainId,secureCookies:new URL(origin).protocol==='https:',getConfig:async()=>JSON.parse(await readFile(manifest,'utf8'))});
app.server.on('error',error=>{console.error(error.code==='EADDRINUSE'?`LostChain metadata port ${port} is already in use.`:'Metadata service failed.');app.provider.destroy();app.db.close();process.exit(1)});
app.server.listen(port,'127.0.0.1',()=>console.log(`LostChain ${network.name} metadata API: http://127.0.0.1:${port}`));
for(const signal of ['SIGINT','SIGTERM'])process.on(signal,async()=>{await app.close();process.exit(0)});
